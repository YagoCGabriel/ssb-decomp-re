#!/usr/bin/env python3
"""Embed one or more SPIR-V binaries as C arrays named <base>_spv[/_len].

Usage: embed_spv.py out.c name1 file1.spv [name2 file2.spv ...]
"""
import sys
argv = sys.argv[1:]
if len(argv) >= 2 and argv[1].endswith('.spv'):
    # legacy single-pair form: name path -> append to default output
    pairs = [(argv[0], argv[1])]
    outpath = '../src/backend/shaders_spv.c'
    mode = 'a'
else:
    outpath = argv[0]
    pairs = [(argv[i], argv[i + 1]) for i in range(1, len(argv), 2)]
    mode = 'w'
chunks = []
for name, path in pairs:
    data = open(path, 'rb').read()
    assert data[:4] == bytes([0x03, 0x02, 0x23, 0x07]), "bad SPIR-V magic"
    out = ['/* generated by shaders/embed_spv.py - do not edit */',
           'const unsigned char %s_spv[] = {' % name]
    line = '    '
    for i, byte in enumerate(data):
        line += '0x%02X,' % byte
        if len(line) > 76:
            out.append(line); line = '    '
    out.append(line.rstrip())
    out.append('};')
    out.append('const unsigned int %s_spv_len = sizeof(%s_spv);' % (name, name))
    chunks.append('\n'.join(out))
open(outpath, mode).write('\n'.join(chunks) + '\n')
