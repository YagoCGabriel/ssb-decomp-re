#!/usr/bin/env python3
"""Embed a SPIR-V binary as a C array named <base>_spv[/_len]."""
import sys
name, path = sys.argv[1], sys.argv[2]
data = open(path, 'rb').read()
assert data[:4] == bytes([0x03, 0x17, 0x07, 0x10]), "bad SPIR-V magic"
out = ['/* generated by shaders/embed_spv.py - do not edit */',
       'const unsigned char %s_spv[] = {' % name]
line = '    '
for i, byte in enumerate(data):
    line += '0x%02X,' % byte
    if len(line) > 76:
        out.append(line); line = '    '
out.append(line.rstrip())
out.append('};')
out.append('const unsigned int %s_spv_len = sizeof(%s_spv);' % (name, name))
open('../src/backend/shaders_spv.c', 'a').write('\n'.join(out) + '\n')
