/* Embedded SPIR-V: generated from shaders/tri.vert + tri.frag with
 *   glslangValidator -V tri.vert -o tri_vert.spv
 *   xxd -i tri_vert.spv
 * The arrays below are placeholders that must be regenerated by the shader
 * build step (shaders/build.sh); on first use we check magic words and fail
 * init gracefully if they were not regenerated. */
extern const unsigned char tri_vert_spv[];
extern const unsigned int tri_vert_spv_len;
