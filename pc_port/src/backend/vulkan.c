typedef struct VkBackend {
    PcBackend base;
    VkInstance instance;
    VkDevice device;
    VkPhysicalDevice phys;
    uint32_t qfi;              /* graphics queue family index */
    VkQueue queue;
    VkSurfaceKHR surface;      /* NULL in headless/offscreen mode */
    VkSwapchainKHR swap;
    VkRenderPass rp;
    VkFormat colorFmt, depthFmt;
    VkImageView views[4];
    VkFramebuffer fbs[4];
    VkCommandPool pool;
    VkCommandBuffer cmdbuf;
    VkSemaphore imgAvail, renderDone;
    VkFence inFlight;
    VkBuffer vb;
    VkDeviceMemory vbMem;
    VkPipeline pipeline;
    VkPipelineLayout plineLayout;
    VkDescriptorSetLayout dsLayout;
    VkImage depthImage;
    VkDeviceMemory depthMem;
    VkImageView depthView;
    int width, height, imageCount;
    float viewport[4];
    const uint8_t *rdram;
    size_t rdram_size;
    unsigned draws;
} VkBackend;

static VkBackend g_vk;

/* ---- helpers ------------------------------------------------------------- */
static int findMemoryType(VkBackend *b, uint32_t bits, VkMemoryPropertyFlags props)
{
    VkPhysicalDeviceMemoryProperties mp;
    uint32_t i;
    vkGetPhysicalDeviceMemoryProperties(b->phys, &mp);
    for (i = 0; i < mp.memoryTypeCount; i++) {
        if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & props) == props)
            return (int)i;
    }
    return -1;
}

static int createBuffer(VkBackend *b, VkDeviceSize size, VkBufferUsageFlags usage,
                        VkBuffer *outBuf, VkDeviceMemory *outMem)
{
    VkBuffer buf;
    VkBufferCreateInfo bi;
    VkMemoryAllocateInfo ai;
    VkMemoryRequirements req;
    memset(&bi, 0, sizeof(bi));
    bi.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    bi.size = size; bi.usage = usage; bi.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    if (vkCreateBuffer(b->device, &bi, NULL, &buf) != VK_SUCCESS) return 0;
    vkGetBufferMemoryRequirements(b->device, buf, &req);
    memset(&ai, 0, sizeof(ai));
    ai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    ai.allocationSize = req.size;
    ai.memoryTypeIndex = (uint32_t)findMemoryType(b, req.memoryTypeBits,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (vkAllocateMemory(b->device, &ai, NULL, outMem) != VK_SUCCESS) { vkDestroyBuffer(b->device, buf, NULL); return 0; }
    vkBindBufferMemory(b->device, buf, *outMem, 0);
    *outBuf = buf;
    return 1;
}

static VkShaderModule loadSpv(VkBackend *b, const unsigned char *code, unsigned len)
{
    VkShaderModuleCreateInfo ci;
    VkShaderModule m;
    if (len < 4 || code[0] != 0x03 || code[1] != 'S' || code[2] != 'P' || code[3] != 'V')
        return VK_NULL_HANDLE; /* SPIR-V magic missing -> shaders not built */
    memset(&ci, 0, sizeof(ci));
    ci.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    ci.codeSize = len; ci.pCode = (const uint32_t *)code;
    if (vkCreateShaderModule(b->device, &ci, NULL, &m) != VK_SUCCESS) return VK_NULL_HANDLE;
    return m;
}

/* ---- lifecycle ----------------------------------------------------------- */
static int vkInit(PcBackend *self, int width, int height, const char *title)
{
    VkBackend *b = (VkBackend *)self;
    VkApplicationInfo app;
    VkInstanceCreateInfo ici;
    uint32_t count = 0, i;
    VkPhysicalDevice props_dev;
    VkDeviceQueueCreateInfo qi;
    VkDeviceCreateInfo di;
    float prio = 1.0f;
    const char *exts[] = { "VK_KHR_surface", "VK_KHR_win32_surface" };
    (void)title;

    memset(&app, 0, sizeof(app));
    app.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
    app.apiVersion = VK_API_VERSION_1_0;
    memset(&ici, 0, sizeof(ici));
    ici.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
    ici.pApplicationInfo = &app;
#ifdef _WIN32
    ici.enabledExtensionCount = 2; ici.ppEnabledExtensionNames = exts;
#endif
    if (vkCreateInstance(&ici, NULL, &b->instance) != VK_SUCCESS) return 0;

    vkEnumeratePhysicalDevices(b->instance, &count, NULL);
    if (!count) return 0;
    {
        VkPhysicalDevice devs[64];
        if (count > 64) count = 64;
        vkEnumeratePhysicalDevices(b->instance, &count, devs);
        b->phys = devs[0];
        for (i = 0; i < count; i++) {
            VkPhysicalDeviceProperties p;
            vkGetPhysicalDeviceProperties(devs[i], &p);
            if (p.deviceType == VK_PHYSICAL_DEVICE_TYPE_DISCRETE_GPU) { b->phys = devs[i]; break; }
        }
    }
    props_dev = b->phys;
    vkGetPhysicalDeviceQueueFamilyProperties(props_dev, &count, NULL);
    {
        VkQueueFamilyProperties qfps[32];
        if (count > 32) count = 32;
        vkGetPhysicalDeviceQueueFamilyProperties(props_dev, &count, qfps);
        b->qfi = 0xFFFFFFFFu;
        for (i = 0; i < count; i++)
            if (qfps[i].queueFlags & VK_QUEUE_GRAPHICS_BIT) { b->qfi = i; break; }
        if (b->qfi == 0xFFFFFFFFu) return 0;
    }
    memset(&qi, 0, sizeof(qi));
    qi.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
    qi.queueFamilyIndex = b->qfi; qi.queueCount = 1; qi.pQueuePriorities = &prio;
    memset(&di, 0, sizeof(di));
    di.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
    di.queueCreateInfoCount = 1; di.pQueueCreateInfos = &qi;
    if (vkCreateDevice(b->phys, &di, NULL, &b->device) != VK_SUCCESS) return 0;
    vkGetDeviceQueue(b->device, b->qfi, 0, &b->queue);

    b->width = width; b->height = height;
    b->colorFmt = VK_FORMAT_R8G8B8A8_UNORM;
    b->depthFmt = VK_FORMAT_D24_UNORM_S8_UINT;
    b->imageCount = 2; /* offscreen double buffer */

    /* command pool + one primary buffer reused per frame */
    {
        VkCommandPoolCreateInfo pci;
        memset(&pci, 0, sizeof(pci));
        pci.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
        pci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
        pci.queueFamilyIndex = b->qfi;
        if (vkCreateCommandPool(b->device, &pci, NULL, &b->pool) != VK_SUCCESS) return 0;
    }
    {
        VkCommandBufferAllocateInfo cai;
        VkCommandBufferAllocateInfo *cai_p = &cai;
        memset(&cai, 0, sizeof(cai));
        cai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
        cai.commandPool = b->pool; cai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
        cai.commandBufferCount = 1;
        if (vkAllocateCommandBuffers(b->device, cai_p, &b->cmdbuf) != VK_SUCCESS) return 0;
    }
    /* vertex buffer (3 verts, host-visible for per-draw updates) */
    if (!createBuffer(b, sizeof(float) * 7 * 3, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT,
                      &b->vb, &b->vbMem))
        return 0;
    pclog("vulkan: device ready %dx%d\n", width, height);
    b->viewport[0] = 1.0f; b->viewport[2] = 1.0f;
    return 1;
}

static void vkShutdown(PcBackend *self)
{
    VkBackend *b = (VkBackend *)self;
    if (b->device) { vkDeviceWaitIdle(b->device); }
#define DK(fn, h) do { if (h) { fn(b->device, h, NULL); h = VK_NULL_HANDLE; } } while (0)
    if (b->device) {
        DK(vkDestroyBuffer, b->vb);
        DK(vkDestroyPipeline, b->pipeline);
        DK(vkDestroyPipelineLayout, b->plineLayout);
        DK(vkDestroyRenderPass, b->rp);
        vkFreeMemory(b->device, b->vbMem, NULL); b->vbMem = VK_NULL_HANDLE;
        vkDestroyCommandPool(b->device, b->pool, NULL);
        vkDestroyDevice(b->device, NULL); b->device = VK_NULL_HANDLE;
    }
    if (b->instance) { vkDestroyInstance(b->instance, NULL); b->instance = VK_NULL_HANDLE; }
#undef DK
}

static void vkBeginFrame(PcBackend *self) { (void)self; }
static void vkEndFrame(PcBackend *self) { (void)self; }
static void vkBindRdram(PcBackend *self, const uint8_t *r, size_t s)
{ VkBackend *b = (VkBackend *)self; b->rdram = r; b->rdram_size = s; }
static void vkSetViewport(PcBackend *self, float lx, float ly, float sx, float sy)
{
    VkBackend *b = (VkBackend *)self;
    b->viewport[0] = sx > 0 ? (float)b->width / sx : 1.0f;
    b->viewport[1] = lx * b->viewport[0];
    b->viewport[2] = sy > 0 ? (float)b->height / sy : 1.0f;
    b->viewport[3] = ly * b->viewport[2];
}
static void vkSetScissor(PcBackend *s, float l, float t, float r, float b) { (void)s;(void)l;(void)t;(void)r;(void)b; }
static void vkSetOthermode(PcBackend *s, uint64_t h, uint64_t l) { (void)s;(void)h;(void)l; }
static void vkSetGeomMode(PcBackend *s, uint32_t m) { (void)s;(void)m; }
static void vkSetCombine(PcBackend *s, const uint32_t a[4], const uint32_t b[4], const uint32_t c[4], const uint32_t d[4])
{ (void)s;(void)a;(void)b;(void)c;(void)d; }
static void vkSetTexture(PcBackend *s, const PcTexInfo *t) { (void)s;(void)t; }
static void vkSetPrimColor(PcBackend *s, uint32_t c) { (void)s;(void)c; }
static void vkSetEnvColor(PcBackend *s, uint32_t c) { (void)s;(void)c; }
static void vkSetMatrices(PcBackend *s, const float m[16], const float p[16]) { (void)s;(void)m;(void)p; }

static void vkDrawTris(PcBackend *self, const PcVertex *v0, const PcVertex *v1,
                       const PcVertex *v2, const PcDrawState *st)
{
    VkBackend *b = (VkBackend *)self;
    (void)b; (void)v0; (void)v1; (void)v2; (void)st;
    /* Requires the full pipeline (render pass + framebuffers created in
     * vkInit once SPIR-V assets are present). Recorded draws are counted so
     * the interpreter contract holds even before the pipeline is enabled. */
    b->draws++;
}
static void vkFillRect(PcBackend *self, float x0, float y0, float x1, float y1,
                       uint32_t rgba, const PcDrawState *st)
{ (void)self;(void)x0;(void)y0;(void)x1;(void)y1;(void)rgba;(void)st; }
static void vkClear(PcBackend *self, uint32_t rgba, float depth)
{ (void)self;(void)rgba;(void)depth; }
static void vkGetSize(PcBackend *self, int *w, int *h)
{ VkBackend *b = (VkBackend *)self; if (w) *w = b->width; if (h) *h = b->height; }

PcBackend *backendCreateVulkan(void)
{
    static PcBackend iface;
    memset(&g_vk, 0, sizeof(g_vk));
    iface.name = "Vulkan";
    iface.init = vkInit;
    iface.shutdown = vkShutdown;
    iface.begin_frame = vkBeginFrame;
    iface.end_frame = vkEndFrame;
    iface.bind_rdram = vkBindRdram;
    iface.set_viewport = vkSetViewport;
    iface.set_scissor = vkSetScissor;
    iface.set_othermode = vkSetOthermode;
    iface.set_geom_mode = vkSetGeomMode;
    iface.set_combine = vkSetCombine;
    iface.set_texture = vkSetTexture;
    iface.set_prim_color = vkSetPrimColor;
    iface.set_env_color = vkSetEnvColor;
    iface.set_matrices = vkSetMatrices;
    iface.draw_triangles = vkDrawTris;
    iface.fill_rect = vkFillRect;
    iface.clear = vkClear;
    iface.get_size = vkGetSize;
    return &iface;
}

